"""The test-reset regrade as Markdown: per chain and arm, then totals per arm type.

Reads `explore-testreset/<chain>/<arm>/grade.json` (`testreset.py grade`) and writes
`explore-testreset/report.md`. Findings prose is added by hand under the generated tables.
"""

from __future__ import annotations

import json
from typing import Any

from .testreset import OUT, arms_of

LABEL = {"N": "N", "Sm": "Sm 2nd", "Sm-nojev1": "Sm 1st", "Nf": "Nf", "Sf": "Sf 2nd",
         "Sf-nojev1": "Sf 1st"}  # fmt: skip
TOTALS = (("N", "Sm", "Sm-nojev1"), ("Nf", "Sf", "Sf-nojev1"))


def load(chain: str, arm: str) -> dict[str, Any] | None:
    path = OUT / chain / arm / "grade.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def sums(bugs: list[dict[str, Any]]) -> tuple[int, int, int]:
    """(F2P passed, F2P total, P2P* broken) over a chain's bugs."""
    return (sum(b["f2p_passed"] for b in bugs), sum(b["f2p"] for b in bugs),
            sum(b["p2p_broken"] for b in bugs))  # fmt: skip


def bug_changes(grade: dict[str, Any]) -> list[str]:
    """Bugs whose resolution differs between the original grade and the reset one."""
    before = {b["instance_id"]: b for b in grade["original"]["bugs"]}
    out = []
    for bug in grade["bugs"]:
        old = before[bug["instance_id"]]
        if old["resolved"] != bug["resolved"]:
            word = "gained" if bug["resolved"] else "lost"
            out.append(f"{word} `{bug['instance_id']}` (F2P {old['f2p_passed']}->"
                       f"{bug['f2p_passed']}/{bug['f2p']}, P2P* broken {old['p2p_broken']}->"
                       f"{bug['p2p_broken']})")  # fmt: skip
    return out


def row(chain: str, arm: str, grade: dict[str, Any]) -> str:
    f0, n0, p0 = sums(grade["original"]["bugs"])
    f1, n1, p1 = sums(grade["bugs"])
    repro = grade.get("repro", {}).get("resolved", "-")
    dropped = ", ".join(f"{d['path']} ({d['status']})" for d in grade["dropped"]) or "-"
    mode = "regraded" if grade["mode"] == "tests-reset" else "unchanged (inspection)"
    changes = "; ".join(bug_changes(grade)) or "-"
    return (f"| {chain} | {LABEL[arm]} | {grade['original']['resolved']} -> {grade['resolved']} | "
            f"{repro} | {f0}->{f1}/{n1} | {p0}->{p1} | {mode} | {dropped} | {changes} |")


def totals(grades: dict[tuple[str, str], dict[str, Any]], arms: tuple[str, ...]) -> list[str]:
    lines = ["| arm | chains | resolved original | resolved tests reset | F2P original | "
             "F2P tests reset | P2P* broken original | P2P* broken tests reset |",
             "|---|---|---|---|---|---|---|---|"]  # fmt: skip
    for arm in arms:
        mine = [g for (_, a), g in grades.items() if a == arm]
        before = [sums(g["original"]["bugs"]) for g in mine]
        after = [sums(g["bugs"]) for g in mine]
        lines.append(f"| {LABEL[arm]} | {len(mine)} | "
                     f"{sum(g['original']['resolved'] for g in mine)}/{5 * len(mine)} | "
                     f"{sum(g['resolved'] for g in mine)}/{5 * len(mine)} | "
                     f"{sum(b[0] for b in before)}/{sum(b[1] for b in before)} | "
                     f"{sum(a[0] for a in after)}/{sum(a[1] for a in after)} | "
                     f"{sum(b[2] for b in before)} | {sum(a[2] for a in after)} |")  # fmt: skip
    return lines


def write(chains: list[str]) -> None:
    grades = {(c, a): g for c in chains for a in arms_of(c) if (g := load(c, a)) is not None}
    lines = ["# Phase A held-out chains graded with the agent's test edits reset", "",
             "Generated by `benchmarks/adopt_explore/report.py`.", "",
             "## Per chain and arm", "",
             "| chain | arm | resolved orig -> reset | repro (orig patch, rebuilt image) | "
             "F2P orig->reset | P2P* broken orig->reset | how | test files dropped | "
             "bug changes |", "|---|---|---|---|---|---|---|---|---|"]  # fmt: skip
    lines += [row(c, a, g) for (c, a), g in grades.items()]
    for arms in TOTALS:
        lines += ["", f"## Totals: {' vs '.join(LABEL[a] for a in arms)}", "", *totals(grades, arms)]
    missing = [f"{c}/{a}" for c in chains for a in arms_of(c) if (c, a) not in grades]
    if missing:
        lines += ["", f"Missing: {', '.join(missing)}"]
    (OUT / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
